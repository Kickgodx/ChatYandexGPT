    @classmethod
    def get_prompt(cls, prompt_type: str = "programmer") -> Dict[str, str]:
        """Получить промпт по типу"""
        return cls.PROMPTS.get(prompt_type, cls.PROMPTS["general"])

    @classmethod
    def get_available_prompts(cls) -> Dict[str, Dict[str, str]]:
        """Получить список доступных промптов"""
        return {key: {"name": value["name"], "description": value["description"]}
                for key, value in cls.PROMPTS.items()}

    @classmethod
    def get_prompt_content(cls, prompt_type: str = "programmer") -> str:
        """Получить содержимое промпта"""
        prompt = cls.get_prompt(prompt_type)
        return prompt["content"]
